export const template = `# セキュリティガイドライン

{{projectName}} プロジェクトのセキュリティガイドライン。

## 基本原則

### MUST NOT

- 機密情報（APIキー、パスワード、トークン等）をコードにハードコードしない
- 機密情報をバージョン管理システムにコミットしない
- 未検証の外部入力を直接実行または評価しない
- 脆弱な暗号化アルゴリズムを使用しない

### MUST

- 機密情報は環境変数または秘密管理ツールで管理する
- すべての外部入力を検証・サニタイズする
- 依存関係の脆弱性を定期的にチェックする（\`npm audit\` 等）
- HTTPS を使用して通信を暗号化する

## 認証・認可

- 認証情報は安全に保管する（ハッシュ化等）
- 最小権限の原則を適用する
- セッション管理を適切に行う
- 多要素認証を推奨する

## 入力値の検証

- ユーザー入力は必ず検証する
- SQLインジェクション、XSS等の攻撃を防ぐ
- ファイルアップロードは種類・サイズを制限する

## 依存関係

- パッケージのバージョンを固定する（lockfile 管理）
- 既知の脆弱性があるパッケージを使用しない
- 不要な依存を最小化する

## 危険操作の事前確認

以下の操作を行う前は、意味・影響範囲・代替案を説明する:

- ファイルの削除（破壊的操作）
- Git 履歴の変更（force push, rebase 等）
- データベースの破壊的操作
- 権限の変更

## インシデント対応

1. セキュリティ問題を発見した場合は直ちに報告
2. 影響範囲を特定し、暫定対応を実施
3. 根本原因を特定し、恒久的な修正を適用
4. 同様の問題の再発防止策を検討
`

